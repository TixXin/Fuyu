// Writes the files generated from the plugin SDK sources and plugins/schema/:
// the single-file SDKs in plugins/sdk/ (for people who copy one file), the copies
// the npm packages publish, protocol.d.mts (names from rpc.json) and the API
// reference docs/plugins/api.md.
// Usage: pnpm sdk:build. tests/scripts/plugin-sdk.test.mjs checks they are current.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { apiReference } from "./plugin-api-doc.mjs";

const SDK_SOURCE = "packages/fuyu-plugin/src";
const PS_MODULE = "packages/powershell/Fuyu.Plugin/Fuyu.Plugin.psm1";
const SCAFFOLD_SDK = "packages/create-fuyu-plugin/sdk";

const lf = (text) => text.replaceAll("\r\n", "\n");
const union = (names) => (names.length === 0 ? "never" : names.map((name) => JSON.stringify(name)).join(" | "));

/** protocol.d.mts: the names in plugins/schema/rpc.json as TypeScript types. */
export function protocolTypes(rpc) {
  const names = (list) => list.map((item) => item.name);
  const permissions = Object.fromEntries(rpc.methods.map((method) => [method.name, method.permission]));
  const lines = [
    "// Generated by `pnpm sdk:build` from plugins/schema/rpc.json; do not edit.",
    "",
    `/** Plugin API versions the island supports: ${rpc.apiVersions.min} to ${rpc.apiVersions.current}. */`,
    `export type ApiVersion = ${union(Array.from({ length: rpc.apiVersions.current - rpc.apiVersions.min + 1 }, (_, index) => rpc.apiVersions.min + index))};`,
    `export type Capability = ${union(names(rpc.capabilities))};`,
    `export type Permission = ${union(names(rpc.permissions))};`,
    `/** Confirmed by the user on the island the first time they are used. */`,
    `export type SensitivePermission = ${union(rpc.permissions.filter((item) => item.sensitive).map((item) => item.name))};`,
    `/** Requests a plugin sends to the island. */`,
    `export type HostMethod = ${union(names(rpc.methods))};`,
    `/** Events for events.subscribe. */`,
    `export type PluginEventName = ${union(names(rpc.events))};`,
    `/** Notifications the island sends to the plugin. */`,
    `export type IslandNotification = ${union(names(rpc.toPlugin))};`,
    "",
    "/** The permission each host method needs (null: none). */",
    "export interface MethodPermissions {",
    ...Object.entries(permissions).map(([name, permission]) => `  ${JSON.stringify(name)}: ${permission === null ? "null" : JSON.stringify(permission)};`),
    "}",
    "",
  ];
  return lines.join("\n");
}

/** The PowerShell module as one dot-sourceable file. */
export function powershellSingleFile(module) {
  const body = lf(module)
    .replace(/^(#[^\n]*\n)+\n/, "")
    .replace(/\n*Export-ModuleMember[^\n]*\n?$/, "\n");
  const header = [
    "# Fuyu plugin helpers for Windows PowerShell 5.1, which every Windows",
    "# 10/11 has, so plugins built on it need nothing installed. This is the",
    "# Fuyu.Plugin module as one file, generated by `pnpm sdk:build` from",
    "# packages/powershell/Fuyu.Plugin/Fuyu.Plugin.psm1. Dot-source it:",
    '#   . "$PSScriptRoot\\lib\\fuyu.ps1"',
    "# Protocol reference: docs/plugins/README.md. Never write other text to stdout;",
    "# use Write-FuyuLog (or stderr) for logs. The function names before the rename,",
    "# *-Focusd*, still work.",
    "",
    "",
  ].join("\n");
  return `${header}${body}`;
}

/** Every generated file: repository-relative path -> contents (LF line ends). */
export function generatedFiles(root) {
  const read = (relative) => lf(readFileSync(path.join(root, relative), "utf8"));
  const rpcText = read("plugins/schema/rpc.json");
  const protocol = protocolTypes(JSON.parse(rpcText));
  const generatedNote = (source) => `// Generated by \`pnpm sdk:build\` from ${source}; edit that file instead.\n`;
  const client = generatedNote(`${SDK_SOURCE}/client.mjs`) + read(`${SDK_SOURCE}/client.mjs`);
  const clientTypes = generatedNote(`${SDK_SOURCE}/client.d.mts`) + read(`${SDK_SOURCE}/client.d.mts`);
  const powershell = powershellSingleFile(read(PS_MODULE));
  return new Map([
    ["packages/fuyu-plugin/schema/manifest.schema.json", read("plugins/schema/manifest.schema.json")],
    ["packages/fuyu-plugin/schema/rpc.json", rpcText],
    [`${SDK_SOURCE}/protocol.d.mts`, protocol],
    ["plugins/sdk/node/fuyu.mjs", client],
    ["plugins/sdk/node/fuyu.d.mts", clientTypes],
    ["plugins/sdk/node/protocol.d.mts", protocol],
    ["plugins/sdk/powershell/fuyu.ps1", powershell],
    [`${SCAFFOLD_SDK}/fuyu.mjs`, client],
    [`${SCAFFOLD_SDK}/fuyu.d.mts`, clientTypes],
    [`${SCAFFOLD_SDK}/protocol.d.mts`, protocol],
    [`${SCAFFOLD_SDK}/fuyu.ps1`, powershell],
    ["docs/plugins/api.md", apiReference(JSON.parse(rpcText))],
  ]);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
  for (const [relative, text] of generatedFiles(root)) {
    mkdirSync(path.dirname(path.join(root, relative)), { recursive: true });
    writeFileSync(path.join(root, relative), text);
  }
  console.log("Wrote the generated plugin SDK files.");
}
