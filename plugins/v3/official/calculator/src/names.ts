const zh = currentLocale() === "zh-CN";

export function unitName(category: string, id: string): string {
  const pair = UNIT_NAMES[`${category}:${id}`];
  return pair ? pair[zh ? 0 : 1] : id;
}

export function currencyName(code: string): string {
  const pair = CURRENCY_NAMES[code];
  return pair ? pair[zh ? 0 : 1] : code;
}
