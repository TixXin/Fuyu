export function lookupTitle(key: string, locale: "zh-CN" | "en"): string | null {
  if (locale === "en") {
    if (EN[key]) return EN[key];
    const parts = key.split("-");
    if (parts.length === 3 && COUSIN_ZH[`${parts[0]}-${parts[1]}`] && (parts[2] === "s" || parts[2] === "d")) return "Cousin";
    return null;
  }
  if (ZH[key]) return ZH[key];
  const parts = key.split("-");
  const cousin = parts.length === 3 ? COUSIN_ZH[`${parts[0]}-${parts[1]}`] : undefined;
  if (cousin && parts[2] === "s") return cousin[0];
  if (cousin && parts[2] === "d") return cousin[1];
  return null;
}

