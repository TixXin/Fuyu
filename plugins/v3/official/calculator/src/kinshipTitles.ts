export function describeChain(chain: Atom[], locale: "zh-CN" | "en"): string {
  const labels = ATOM_LABEL[locale];
  if (locale === "en") return chain.length === 0 ? "You" : ["Your", ...chain.map((atom) => labels[atom].toLowerCase())].join(" → ");
  return chain.length === 0 ? "自己" : `我的${chain.map((atom) => labels[atom]).join("的")}`;
}

