export const TEXT: Record<Locale, typeof zhCN> = { "zh-CN": zhCN, en };

export function textFor(locale: Locale = currentLocale()): typeof zhCN {
  return TEXT[locale];
}

export const PAGE_TITLE = { "zh-CN": zhCN.title, en: en.title };

export const SETUP_HINT = { "zh-CN": zhCN.setupHint, en: en.setupHint };

export function problemText(problem: WeatherProblem | null, copy: typeof zhCN): string | null {
  if (!problem) return null;
  return problem.kind === "noPlace" ? copy.noPlace(problem.city) : copy.offline(problem.reason);
}
